    public static void play(Entity entity, String character, String cue) {
        List<String> sounds = CUES.get(character + "|" + cue);
        if (sounds == null && "luna".equals(character)) sounds = CUES.get("cat|" + cue);
        if (sounds == null) return;
        RandomSource random = entity.getRandom();
        for (String descriptor : sounds) {
            int marker = descriptor.lastIndexOf('#');
            String sound = marker < 0 ? descriptor
                    : descriptor.substring(0, marker) + random.nextInt(Integer.parseInt(descriptor.substring(marker + 1)));
            SoundEvent event = SoundEvent.createVariableRangeEvent(Identifier.fromNamespaceAndPath("sexmod", sound));
            float pitch = 0.96F + random.nextFloat() * 0.08F;
            entity.level().playLocalSound(entity.getX(), entity.getY(), entity.getZ(), event, SoundSource.NEUTRAL, 1.0F, pitch, false);
        }
    }
